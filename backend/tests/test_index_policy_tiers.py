"""Phase E's pure decisions: what gets indexed, which project it belongs to,
what it costs to describe, and how it gets cut up.

All four are plain functions over plain data — no database, no model, no index —
which is the point of having factored them out of the indexer. The hash chain
gets its own file (test_content_addressing.py) because the guarantees it makes
are about sequences of commits rather than single calls.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from bridge import config
from bridge.index import chunking, policy, projects, tiers


# ------------------------------------------------------------------ policy


def test_the_default_denylist_covers_the_things_nobody_asks_questions_about():
    p = policy.Policy.default("demo")
    for path in (
        "node_modules/react/index.java",
        "web/node_modules/x/y.java",
        "vendor/lib.java",
        "src/generated/Api.java",
        "app/__snapshots__/Thing.java",
        "test/fixtures/sample.java",
        "static/app.min.java",
        "proto/user.pb.java",
    ):
        assert p.decide(path, 10) == policy.DENYLISTED, path


def test_a_real_source_file_is_indexed():
    p = policy.Policy.default("demo")
    assert p.decide("src/main/java/com/x/OwnerController.java", 4_000) is None


def test_a_file_bridge_has_no_parser_for_is_excluded_as_such():
    """Distinct from the denylist: `.md` isn't unwanted, it's unparseable here."""
    p = policy.Policy.default("demo")
    assert p.decide("README.md", 100) == policy.NOT_A_SOURCE_FILE


def test_the_size_cap_bites():
    p = policy.Policy.default("demo")
    assert p.decide("src/Big.java", config.INDEX_MAX_FILE_BYTES + 1) == policy.TOO_LARGE


def test_source_roots_are_an_allowlist_when_set():
    p = policy.Policy(source_roots=("src/main",), extensions=(".java",))
    assert p.decide("src/main/A.java", 10) is None
    assert p.decide("src/test/A.java", 10) == policy.NOT_IN_SOURCE_ROOT


