def test_apply_reports_a_reason_and_examples_for_every_exclusion(tmp_path: Path):
    """An excluded file and a file the parser crashed on both look like absence.
    The counts are the only thing that tells them apart."""
    (tmp_path / "src").mkdir()
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "src" / "Good.java").write_text("class Good {}", encoding="utf-8")
    (tmp_path / "node_modules" / "Bad.java").write_text("class Bad {}", encoding="utf-8")
    (tmp_path / "README.md").write_text("# hi", encoding="utf-8")
    (tmp_path / "src" / "Gen.java").write_text("// @generated\nclass Gen {}", encoding="utf-8")

    result = policy.apply(
        tmp_path,
        ["src/Good.java", "node_modules/Bad.java", "README.md", "src/Gen.java"],
        policy.Policy.default("demo"),
    )
    assert result.included == ["src/Good.java"]
    assert result.excluded[policy.DENYLISTED] == 1
    assert result.excluded[policy.NOT_A_SOURCE_FILE] == 1
    assert result.excluded[policy.GENERATED] == 1
    assert result.total_excluded == 3
    assert result.examples[policy.DENYLISTED] == ["node_modules/Bad.java"]


def test_a_config_denylist_extends_the_defaults_rather_than_replacing_them(tmp_path: Path):
    (tmp_path / "index_policy.demo.yaml").write_text(
        "deny:\n  - '**/legacy/**'\n", encoding="utf-8"
    )
    p = policy.Policy.load("demo", config_root=tmp_path)
    assert p.decide("src/legacy/Old.java", 10) == policy.DENYLISTED  # from the config
    assert p.decide("node_modules/x.java", 10) == policy.DENYLISTED  # still from the defaults


def test_a_missing_policy_file_is_not_an_error(tmp_path: Path):
    assert policy.Policy.load("nothing-here", config_root=tmp_path).deny


# ------------------------------------------------------------------ projects


def test_maven_modules_become_projects(tmp_path: Path):
    (tmp_path / "pom.xml").write_text(
        "<project><modules><module>core</module><module>web</module></modules></project>",
        encoding="utf-8",
    )
    found = {p.root_path: p for p in projects.detect(tmp_path, "demo")}
    assert set(found) >= {"", "core", "web"}
    assert found["core"].kind == projects.MAVEN


def test_gradle_includes_become_projects(tmp_path: Path):
    (tmp_path / "settings.gradle").write_text("include ':app:core'\ninclude 'lib'\n", encoding="utf-8")
    found = {p.root_path for p in projects.detect(tmp_path, "demo")}
    assert {"app/core", "lib"} <= found


def test_npm_workspaces_become_projects(tmp_path: Path):
    (tmp_path / "package.json").write_text(
        '{"name": "root", "workspaces": ["packages/*"]}', encoding="utf-8"
    )
    (tmp_path / "packages" / "ui").mkdir(parents=True)
    (tmp_path / "packages" / "api").mkdir(parents=True)
    found = {p.root_path for p in projects.detect(tmp_path, "demo")}
    assert {"packages/ui", "packages/api"} <= found


def test_go_work_becomes_projects(tmp_path: Path):
    (tmp_path / "go.work").write_text("go 1.22\n\nuse (\n\t./svc\n\t./cli\n)\n", encoding="utf-8")
    found = {p.root_path for p in projects.detect(tmp_path, "demo")}
    assert {"svc", "cli"} <= found


def test_a_repo_that_declares_nothing_still_gets_one_project(tmp_path: Path):
    """`chunks.project` is non-null for every chunk; "unassigned" is not an answer."""
    (tmp_path / "src").mkdir()
    found = projects.detect(tmp_path, "demo")
    assert len(found) == 1 and found[0].kind == projects.ROOT


def test_the_deepest_matching_root_wins(tmp_path: Path):
    index = projects.ProjectIndex(
        [
            projects._make("demo", "", "root", projects.MAVEN),
            projects._make("demo", "services", "services", projects.MAVEN),
            projects._make("demo", "services/billing", "billing", projects.MAVEN),
        ]
    )
    assert index.of("services/billing/src/A.java") == "demo:services/billing"
    assert index.of("services/other/src/A.java") == "demo:services"
    assert index.of("README.md") == "demo:."


# ------------------------------------------------------------------ tiering


def _tier(**kwargs):
    base = dict(
        kind="method", name="doThing", attrs={}, line_count=20, semantic_in_degree=0,
        io_role=config.IO_NONE, io_source="", vocab_hit=False,
    )
    base.update(kwargs)
    return tiers.tier_for(**base)


@pytest.mark.parametrize("name", ["getName", "setCity", "isNew", "hasErrors"])
def test_short_accessors_are_template_tier(name):
    tier, _ = _tier(name=name, line_count=3)
    assert tier == tiers.T0


@pytest.mark.parametrize("name", ["getting", "settle", "island", "hash"])
def test_words_that_merely_start_like_accessors_are_not_accessors(name):
    """`startswith("is")` would sweep up `island`. The capital is the test."""
    assert not tiers.is_accessor(name)


def test_a_long_accessor_is_not_trivial():
    """A 40-line `getX` is doing something a getter should not; describe it."""
    tier, _ = _tier(name="getReport", line_count=40)
    assert tier == tiers.T2


def test_boilerplate_names_are_template_tier():
    assert _tier(name="toString", line_count=3)[0] == tiers.T0
    assert _tier(name="hashCode", line_count=3)[0] == tiers.T0


def test_a_constructor_is_template_tier():
    assert _tier(name="Owner", attrs={"is_constructor": True}, line_count=4)[0] == tiers.T0


@pytest.mark.parametrize("kind", ["endpoint", "entity", "screen"])
def test_the_product_surface_is_always_full_tier(kind):
    """Even a one-line endpoint is the thing product people ask about."""
    tier, reason = _tier(kind=kind, name="x", line_count=1)
    assert tier == tiers.T2 and "product surface" in reason


def test_a_persisting_write_is_promoted_however_small():
    tier, reason = _tier(
        name="save", line_count=2, io_role=config.IO_WRITE,
        io_source=config.IO_SOURCE_ROUTE,
    )
    assert tier == tiers.T2


def test_a_route_handler_is_promoted():
    tier, reason = _tier(name="x", line_count=2, io_source=config.IO_SOURCE_ROUTE)
    assert tier == tiers.T2 and "route" in reason


def test_a_hub_is_promoted_however_trivial_it_looks():
    tier, reason = _tier(name="getName", line_count=2, semantic_in_degree=20)
    assert tier == tiers.T2 and "hub" in reason


def test_a_vocabulary_hit_is_promoted():
    tier, reason = _tier(name="getName", line_count=2, vocab_hit=True)
    assert tier == tiers.T2 and "vocabulary" in reason


def test_promotion_beats_demotion_when_both_rules_match():
    """`getName` is an accessor AND a hub. Tiering up on ambiguity is the whole
    stated bias: a wrongly-T0 chunk is a permanent hole, a wrongly-T2 chunk costs
    a fraction of a cent."""
    assert _tier(name="getName", line_count=2, semantic_in_degree=99)[0] == tiers.T2


def test_something_with_real_work_in_it_is_full_tier():
    tier, _ = _tier(name="process", line_count=40, attrs={"invocation_count": 9})
    assert tier == tiers.T2


def test_template_descriptions_say_only_what_the_signature_says():
    assert tiers.template_description("method", "getLastName", {}, "Owner") == (
        "Reads the last name on Owner."
    )
    assert tiers.template_description("method", "setCity", {}, "Owner") == "Sets the city on Owner."
    assert tiers.template_description("method", "Owner", {"is_constructor": True}, "Owner") == (
        "Creates a Owner."
    )


def test_the_complexity_proxy_reads_the_attrs_the_parser_actually_writes():
    """Regression: these two keys did not exist on node attrs when tiers.py was
    first written, so the proxy silently scored every method zero."""
    assert tiers.complexity_proxy({"invocation_count": 3, "identifier_count": 10}) == 16
    assert tiers.complexity_proxy({}) == 0


# ------------------------------------------------------------------ chunking


def _source(lines: int) -> str:
    return "\n".join(f"line {i}" for i in range(1, lines + 1))


def test_a_short_method_stays_one_chunk():
    chunks = chunking.split_method(
        source=_source(50), name="m", qualified_name="C#m", start_line=10, end_line=40
    )
    assert len(chunks) == 1
    assert (chunks[0].start_line, chunks[0].end_line) == (10, 40)


def test_a_long_method_is_split_with_overlap_and_keeps_real_line_numbers():
    chunks = chunking.split_method(
        source=_source(400), name="big", qualified_name="C#big",
        start_line=1, end_line=300, owner="C", signature="big()",
    )
    assert len(chunks) > 1
    # every citation still resolves to the lines it actually covers
    assert chunks[0].start_line == 1
    assert chunks[-1].end_line == 300
    # consecutive windows overlap rather than butting up against each other
    assert chunks[1].start_line < chunks[0].end_line


def test_every_part_after_the_first_carries_its_context():
    chunks = chunking.split_method(
        source=_source(400), name="big", qualified_name="C#big",
        start_line=1, end_line=300, owner="OwnerController", signature="big()",
    )
    assert "OwnerController.big()" in chunks[1].code
    assert "part 2 of" in chunks[1].code


def test_parts_get_distinct_qualified_names():
    """Identical qualified names would collide into one identity and one
    description, which is the bug sub-chunking exists to avoid."""
    chunks = chunking.split_method(
        source=_source(400), name="big", qualified_name="C#big", start_line=1, end_line=300
    )
    names = [c.qualified_name for c in chunks]
    assert len(names) == len(set(names))


def test_a_type_header_is_synthesised_not_sliced():
    """The first N lines of a file are imports. What answers "what is this class
    for" is the declaration plus fields plus what it can do."""
    chunk = chunking.type_header_chunk(
        source=_source(200), type_name="Owner", qualified_name="com.x.Owner",
        start_line=20, end_line=180,
        fields=["String lastName", "List<Pet> pets"],
        method_names=["addPet(Pet)", "getPets()"],
        annotations=["Entity"],
    )
    assert "@Entity" in chunk.code
    assert "String lastName" in chunk.code
    assert "addPet(Pet)" in chunk.code
    assert chunk.attrs["synthesised"] is True
    # the span still points at the real declaration, so the citation opens
    assert (chunk.start_line, chunk.end_line) == (20, 180)


def test_a_short_template_stays_one_chunk():
    chunks = chunking.split_template(source=_source(30), name="page", qualified_name="s:page")
    assert len(chunks) == 1


def test_a_long_template_splits_on_its_sections():
    body = ["<html>", "<head></head>"] + ["x"] * 100 + ["<form>", "y", "</form>"] + ["<table>"] + ["z"] * 60
    chunks = chunking.split_template(
        source="\n".join(body), name="ownerDetails", qualified_name="screen:owners/ownerDetails"
    )
    assert len(chunks) >= 3  # preamble + form + table
    assert chunks[0].start_line == 1
    assert chunks[-1].end_line == len(body)


def test_a_long_template_with_no_sections_degrades_to_one_chunk():
    """Crude section-finding must fail safe: exactly today's behaviour, not worse."""
    chunks = chunking.split_template(
        source=_source(400), name="blob", qualified_name="screen:blob"
    )
    assert len(chunks) == 1
